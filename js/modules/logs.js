// ===== LOG STORAGE =====
const logStore = {
  logs: [],
  
  // Add log entry
  addLog: function(category, action, details, status = 'SUCCESS', memberId = null) {
    const logEntry = {
      id: `log_${Date.now()}_${Math.random().toString(36).substr(2, 9)}`,
      timestamp: new Date().toISOString(),
      date: new Date().toLocaleDateString('en-US'),
      time: new Date().toLocaleTimeString('en-US'),
      category: category,
      action: action,
      details: details,
      status: status,
      memberId: memberId || window.appState?.member?.id,
      memberName: window.appState?.member?.fullName || 'System',
      userRole: window.appState?.role || 'UNKNOWN'
    };
    
    this.logs.push(logEntry);
    localStorage.setItem('clubLogs', JSON.stringify(this.logs));
    console.log(`📝 Log added: ${category} - ${action}`);
    return logEntry;
  },

  // Get all logs
  getAllLogs: function() {
    return this.logs;
  },

  // Filter logs by criteria
  filterLogs: function(filters = {}) {
    return this.logs.filter(log => {
      if (filters.category && log.category !== filters.category) return false;
      if (filters.action && log.action !== filters.action) return false;
      if (filters.status && log.status !== filters.status) return false;
      if (filters.memberId && log.memberId !== filters.memberId) return false;
      if (filters.dateFrom && new Date(log.timestamp) < new Date(filters.dateFrom)) return false;
      if (filters.dateTo && new Date(log.timestamp) > new Date(filters.dateTo)) return false;
      return true;
    });
  },

  // Load logs from storage
  loadLogs: function() {
    const stored = localStorage.getItem('clubLogs');
    if (stored) {
      this.logs = JSON.parse(stored);
    }
  }
};

// Load logs on initialization
logStore.loadLogs();

