// ===== EXPORT LOGS =====
window.exportLogs = function(format = 'json') {
  const logs = logStore.getAllLogs();
  
  if (format === 'csv') {
    let csv = 'Date,Time,Category,Action,Details,Status,Member\n';
    logs.forEach(log => {
      csv += `"${log.date}","${log.time}","${log.category}","${log.action}","${log.details}","${log.status}","${log.memberName}"\n`;
    });
    return csv;
  }
  
  return JSON.stringify(logs, null, 2);
};

// ===== PRINT LOGS =====
window.printLogs = function(filters = {}) {
  const logs = logStore.filterLogs(filters);
  const printWindow = window.open('', '', 'height=600,width=800');
  
  let html = `
    <html>
      <head>
        <title>Indian Club Bahrain - Activity Logs</title>
        <style>
          body { font-family: Arial, sans-serif; margin: 20px; }
          h1 { color: #333; }
          table { width: 100%; border-collapse: collapse; margin-top: 20px; }
          th, td { border: 1px solid #ddd; padding: 8px; text-align: left; }
          th { background-color: #667eea; color: white; }
          tr:nth-child(even) { background-color: #f9f9f9; }
          .success { color: #2ed573; }
          .warning { color: #ffa502; }
          .failed { color: #ff6b6b; }
        </style>
      </head>
      <body>
        <h1>Indian Club Bahrain - Activity Logs</h1>
        <p>Generated: ${new Date().toLocaleString()}</p>
        <p>Total Records: ${logs.length}</p>
        <table>
          <thead>
            <tr>
              <th>Date & Time</th>
              <th>Category</th>
              <th>Action</th>
              <th>Details</th>
              <th>Status</th>
              <th>Member</th>
            </tr>
          </thead>
          <tbody>
  `;
  
  logs.forEach(log => {
    const statusClass = log.status === 'SUCCESS' ? 'success' : log.status === 'WARNING' ? 'warning' : 'failed';
    html += `
      <tr>
        <td>${log.date} ${log.time}</td>
        <td>${log.category}</td>
        <td>${log.action}</td>
        <td>${log.details}</td>
        <td class="${statusClass}">${log.status}</td>
        <td>${log.memberName}</td>
      </tr>
    `;
  });
  
  html += `
          </tbody>
        </table>
      </body>
    </html>
  `;
  
  printWindow.document.write(html);
  printWindow.document.close();
  printWindow.print();
};

// ===== CLEAR OLD LOGS (Keep last 90 days) =====
window.clearOldLogs = function() {
  const ninetyDaysAgo = new Date();
  ninetyDaysAgo.setDate(ninetyDaysAgo.getDate() - 90);
  
  logStore.logs = logStore.logs.filter(log => {
    return new Date(log.timestamp) > ninetyDaysAgo;
  });
  
  localStorage.setItem('clubLogs', JSON.stringify(logStore.logs));
  console.log('✅ Old logs cleared (kept last 90 days)');
};

